import type { Overview } from './api';
import { exceptionsLink, inr, linkTo } from './format';
import { Icon, type IconName } from './Icons';
import { Reveal } from './ui';

// Reports and exports: what the run closes into for the books, then every file the server writes, each with what
// it is for. The files are the API's own (/runs/:id/<file>); nothing here is computed in the browser.

const FILES: { name: string; title: string; kind: string; icon: IconName; text: string }[] = [
  {
    name: 'journal-lines.csv',
    title: 'Journal lines for Tally',
    kind: 'CSV',
    icon: 'book',
    text: 'One row per ledger line, for TallyPrime’s Excel import. Save as .xlsx first.',
  },
  {
    name: 'journal-entries.csv',
    title: 'Journal entries',
    kind: 'CSV',
    icon: 'layers',
    text: 'Vouchers as debit and credit pairs: fees, GST, refunds and chargebacks.',
  },
  {
    name: 'exceptions.csv',
    title: 'Exceptions',
    kind: 'CSV',
    icon: 'search',
    text: 'One row per exception: age, next step, checker verdict and any decision.',
  },
  {
    name: 'report.json',
    title: 'Full run report',
    kind: 'JSON',
    icon: 'code',
    text: 'Everything on the overview, every exception and voucher, in integer paise.',
  },
  {
    name: 'report.csv',
    title: 'Run summary',
    kind: 'CSV',
    icon: 'file',
    text: 'The overview as spreadsheet rows.',
  },
];

export function Reports({ runId, o }: { runId: string; o: Overview | null }) {
  return (
    <div className="reports">
      {o ? (
        <Reveal>
          <section className="report-strip" aria-label="What this run closes into">
            <div>
              <span className="kicker">Vouchers for the books</span>
              <b className="serif">{o.journal.vouchers}</b>
              <span>
                for {o.journal.settlementsBooked} bank-confirmed settlements
                {o.journal.adjustmentsBooked > 0
                  ? ` and ${o.journal.adjustmentsBooked} approved adjustments`
                  : ''}
              </span>
            </div>
            <div>
              <span className="kicker">Not bookable yet</span>
              <b className="serif">{o.journal.settlementsNotBooked.count}</b>
              <span>{inr(o.journal.settlementsNotBooked.paise)}, with no bank credit matched</span>
            </div>
            <div>
              <span className="kicker">Fee overcharged</span>
              <b className="serif">{inr(o.leakage.excessPaise)}</b>
              <span>{o.leakage.overchargedCount} payments to raise with Razorpay</span>
            </div>
            <div>
              <span className="kicker">Still unreconciled</span>
              <b className="serif">
                {inr(String(BigInt(o.gap.openPaise) + BigInt(o.gap.awaitingPaise)))}
              </b>
              <span>
                <a href={exceptionsLink(runId, {})}>
                  {o.gap.cases.open + o.gap.cases.awaiting} cases to review →
                </a>
              </span>
            </div>
          </section>
        </Reveal>
      ) : null}

      <div className="section-head">
        <h2 className="serif">Exports</h2>
        <p className="muted">Generated by the server from this run, in integer paise.</p>
      </div>
      <ul className="dl-grid">
        {FILES.map((f, i) => (
          <Reveal key={f.name} i={i}>
            <li>
              <a className="card dl-card" href={`/runs/${runId}/${f.name}`} download>
                <span className="dl-ico">
                  <Icon name={f.icon} size={18} />
                </span>
                <span className="dl-kind">{f.kind}</span>
                <b>{f.title}</b>
                <span className="muted">{f.text}</span>
                <span className="dl-go">
                  <Icon name="download" size={14} /> {f.name}
                </span>
              </a>
            </li>
          </Reveal>
        ))}
      </ul>

      <a className="card audit-cta" href={linkTo(runId, 'audit')}>
        <span className="dl-ico">
          <Icon name="list" size={18} />
        </span>
        <span>
          <b>Audit trail</b>
          <span className="muted">
            Every import, rule match, proposal, verdict and decision on any record, in order.
          </span>
        </span>
        <Icon name="arrow" size={16} />
      </a>
    </div>
  );
}
